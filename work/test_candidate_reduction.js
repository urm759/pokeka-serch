const assert=require('node:assert/strict'),fs=require('node:fs');
const model=require('../candidate-reduction-model');
const {extraUrl,withClock,pack,unpack,jstDay}=require('./audit_candidate_reduction');
const row=(selected,exclusions=[])=>({name:'test',selected,preset:true,now:false,purchaseState:'expired',periodHeld:true,exclusions});
const before={rows:{a:row(true),b:row(false,['既存不足']),c:row(true)}};
const after={rows:{a:row(false,['期限切れ','出口不足','期限切れ']),b:row(false,['既存不足','利益']),c:row(true),d:row(true)}};
assert.deepEqual(unpack(pack(after)),after,'compressed backend history preserves all rows, including null/negative/zero values');
assert.equal(jstDay('2026-10-12T14:59:59Z'),'2026-10-12');assert.equal(jstDay('2026-10-12T15:00:00Z'),'2026-10-13');
const diff=model.compare(before,after);
assert.equal(diff.lostCount,1);assert.equal(diff.addedCards,1);assert.equal(diff.newSelected,1);
assert.deepEqual(diff.overlap,{'期限切れ':1,'出口不足':1});
assert.equal(Object.values(diff.sequential).reduce((a,b)=>a+b,0),diff.lostCount);
assert.equal(diff.lost[0].preexisting.length,0,'unchanged insufficiency in other cards is not a new departure');
assert.equal(model.counts(after.rows).periodHeld,2,'period hold is independent of selection and GO');
assert.equal(model.counts(after.rows).now,0);
assert.deepEqual(Object.keys(model.recoveryTargets({...after.rows,c:{...after.rows.c,specificationHeld:true}})),['d']);
assert.equal(model.recoveryTargets({a:{...row(true),holds:['価格対立・誤紐付け']}}).a,undefined);
