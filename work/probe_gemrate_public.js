// One normal public-page request. No API, cookies, challenges, or raw-data publication.
const URL='https://www.gemrate.com/item-details?category=tcg-cards&grader=psa&set_name=Pokemon+Japanese+Sword+%26+Shield+Eevee+Heroes&year=2021';
async function probe(fetcher=fetch) {
  const startedAt=new Date().toISOString(),start=performance.now();
  const result={version:1,environment:process.env.GITHUB_ACTIONS==='true'?'GitHub Actions':'PC HTTP',startedAt,
    pageUrl:URL,requests:1,retries:0,apiCalls:0,llmCalls:0,codexCalls:0,
    rawPublished:false,populationImported:0,scheduledCollectionEnabled:false};
  try {
    const response=await fetcher(URL,{redirect:'manual',headers:{'User-Agent':'pokeka-gemrate-public-compatibility-check'},signal:AbortSignal.timeout(25000)});
    const body=await response.text();
    result.httpStatus=response.status;result.responseBytes=Buffer.byteLength(body);
    result.contentEncoding=response.headers.get('content-encoding');
    result.declaredTransferBytes=Number(response.headers.get('content-length'))||null;
    if(response.status===403||response.status===401||/Just a moment|cf-chl-|captcha/i.test(body)) {
      result.status='access-held';result.sourceSucceeded=false;result.nextAction='Stop this route. No alternate headers, credentials, or challenge bypass.';
    } else if(response.status===429) {
      result.status='rate-limited';result.sourceSucceeded=false;result.retryAfter=response.headers.get('retry-after');
    } else if(!response.ok) {result.status=response.status>=500?'temporary-failure':'http-failure';result.sourceSucceeded=false;}
    else {
      result.sourceSucceeded=true;
      result.pageUpdatedDate=body.match(/Updated:\s*(\d{4}-\d{2}-\d{2})/)?.[1]||null;
      result.csvButtonPresent=/id=["']csv_download["']/.test(body);
      result.clientCsvExport=/exportDataAsCsv/.test(body);
      result.directCsvLinkPresent=/href=["'][^"']+\.csv(?:\?[^"']*)?["']/i.test(body);
      result.embeddedRowDataPresent=/rowData\s*[:=]\s*\[/.test(body);
      result.status='public-page-received-csv-not-verified';
      result.nextAction=result.clientCsvExport?'Normal CSV is generated by the page. Browser export on cloud remains unimplemented/unverified; do not invent a CSV endpoint.'
        :'Confirm the ordinary export mechanism before connecting collection.';
    }
  } catch(error) {result.status='transport-failure';result.sourceSucceeded=false;result.error=error.name==='TimeoutError'?'timeout':String(error.message).slice(0,160);}
  result.durationMs=Math.round(performance.now()-start);result.endedAt=new Date().toISOString();
  return result;
}
if(require.main===module)probe().then(result=>{
  // Metrics only: public Actions logs/artifacts must not contain the HTML or POP rows.
  const text=JSON.stringify(result);console.log(text);
  if(process.env.PROBE_METRICS_FILE)require('node:fs').writeFileSync(process.env.PROBE_METRICS_FILE,text);
});
module.exports={probe};
