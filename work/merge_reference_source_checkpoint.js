// Reconcile committed acquisition snapshots without reacquiring or forcing Git.
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const read=(ref,file)=>JSON.parse(cp.execFileSync('git',['show',`${ref}:${file}`],{cwd:root,maxBuffer:80e6}));
const write=(file,value)=>fs.writeFileSync(path.join(root,file),JSON.stringify(value));
const stamp=r=>Math.max(0,...['observedAt','priceObservedAt','stockObservedAt','updatedAt'].map(k=>Date.parse(r?.[k])||0));
function merge(left='HEAD',right='origin/main') {
  const conflicts=cp.execFileSync('git',['diff','--name-only','--diff-filter=U'],{cwd:root,encoding:'utf8'}).trim().split('\n');
  const allowed=['work/hareruya2_catalog.json','work/hareruya2_stock_history.json','data/hareruya2-stock-summary.json','data/link-coverage.json','data/ui/hareruya2-stock-summary.json','data/ui/manifest.json'];
  assert(conflicts.every(f=>allowed.includes(f)),'Unknown conflicts require review');
  const dir=path.join(root,'work/logs/reference-source-merge-'+Date.now());fs.mkdirSync(dir,{recursive:true});
  for(const f of allowed.filter(f=>!f.startsWith('data/ui/'))) for(const [name,ref]of [['left',left],['right',right]]) fs.writeFileSync(path.join(dir,name+'-'+path.basename(f)),JSON.stringify(read(ref,f)));
  const ca=read(left,allowed[0]),cb=read(right,allowed[0]);
  const key=r=>[r.detailUrl,r.cardId,r.state].join('|');
  const catalog=[...new Map([...ca,...cb].sort((a,b)=>stamp(a)-stamp(b)).map(r=>[key(r),r])).values()];
  for(const r of [...ca,...cb]) assert(stamp(catalog.find(x=>key(x)===key(r)))>=stamp(r),'Never regress individual confirmation');
  write(allowed[0],catalog);
  const sa=read(left,allowed[2]),sb=read(right,allowed[2]),cards={};
  for(const id of new Set([...Object.keys(sa.cards),...Object.keys(sb.cards)])) {const a=sa.cards[id],b=sb.cards[id];cards[id]=!a?b:!b?a:stamp(a)>=stamp(b)?a:b;}
  write(allowed[2],{...sa,cards});
  const ha=read(left,allowed[1]),hb=read(right,allowed[1]),dates=[...new Set([...ha.dates,...hb.dates])].sort(),stocks={};
  const times=rows=>Object.fromEntries(rows.filter(r=>r.cardId).map(r=>[r.cardId,stamp(r)]));const ta=times(ca),tb=times(cb);
  for(const id of new Set([...Object.keys(ha.stocks),...Object.keys(hb.stocks)])) stocks[id]=dates.map(d=>{const a=ha.stocks[id]?.[ha.dates.indexOf(d)],b=hb.stocks[id]?.[hb.dates.indexOf(d)];return a==null?b??null:b==null?a:(ta[id]||0)>=(tb[id]||0)?a:b;});
  write(allowed[1],{dates,stocks});
  // Derived audits/UI hashes are regenerated by their normal builders before publication.
  write(allowed[3],read(left,allowed[3]));
  require('./audit_link_coverage.js');
  require('./build_ui_data.js').build(root);
  return {catalog:catalog.length,summaryCards:Object.keys(cards).length,recovery:dir,networkRequests:0};
}
if(require.main===module)console.log(JSON.stringify(merge()));
module.exports={merge};
