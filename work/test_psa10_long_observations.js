const assert = require('node:assert/strict');
const { dailyRows, statistics, observationStatus } = require('./build_psa10_period_statistics');
const { build } = require('./build_psa10_period_statistics');
const { appendCurrent, HISTORY_DAYS } = require('./build_market_analysis');
const { identity, confirmation } = require('./psa10_observation_evidence');
const card = { id: 'fixture', identityKey: 'SET|001|JA|normal', price: 100, snkPsa10Price: 200 };
const at = i => new Date(Date.UTC(2026,9,13)-i*86400000).toISOString().slice(0,10);
const row = i => [at(i),100,200+i,null,null,null,null,null,null,null,[at(i)+'T03:00:00Z',identity(card)]];
const full = dailyRows(Array.from({length:201},(_,i)=>row(i)),card);
const earlier=row(0),later=row(0);later[2]=500;later[10]=[at(0)+'T05:00:00Z',identity(card)];
assert.equal(dailyRows([later,earlier],card)[0][2],500,'same-day receipts use the latest confirmation, not file order');
let stat = statistics(full,at(0),200,0,2);
assert.equal(stat.count,200); assert.equal(stat.mean,299.5); assert.equal(stat.median,299.5);
assert.equal(stat.missingDays,0); assert(observationStatus(stat,200,at(0)).completeCalendarWindow);
const sparse = dailyRows([row(0),row(199),row(200),row(0),[at(1),100,900,null,null,null,null,null,null,null,null]],card);
stat=statistics(sparse,at(0),200,0,2);
assert.equal(stat.count,2); assert.equal(stat.missingDays,198); assert.equal(stat.mean,299.5);
assert(observationStatus(stat,200,at(0)).status.includes('2/200'));
assert.equal(dailyRows([row(0)],{...card,identityKey:'other mirror'}).length,0);
assert.equal(dailyRows([[at(0),1,2,null,null,null,null,null,null,null,[at(1),identity(card)]]],card).length,0);
const legacy=dailyRows([[at(0),1,200]],card);
assert(observationStatus(statistics(legacy,at(0),200,0,2),200,at(0)).status.includes('旧記録'));
assert.equal(statistics([],at(0),200,0,2).mean,null);
assert.equal(statistics([['2026-02-31',1,200]],'2026-03-03',200,0,2).mean,null,'invalid dates must not normalize into another calendar day');
const meta={generatedAt:at(0)+'T03:00:00Z'};
const sourceRun={status:'success',acquiredCount:1,lastSuccessAt:meta.generatedAt};
assert(confirmation(card,at(0),{meta,sourceRun}));
assert.equal(confirmation(card,at(0),{meta,sourceRun,sourceIdentities:new Map()}),null,'a catalog-wide date cannot refresh a retained absent card');
assert.equal(confirmation(card,at(0),{meta,sourceRun,sourceIdentities:new Map([[card.id,'other variant']])}),null);
for(const source of [{...sourceRun,status:'failed'},{...sourceRun,acquiredCount:0},{...sourceRun,lastSuccessAt:at(1)+'T03:00:00Z'}]) assert.equal(confirmation(card,at(0),{meta,sourceRun:source}),null);
assert.equal(confirmation({...card,psa10ObservedAt:at(1)},at(0),{meta,sourceRun}),null,'old retained field cannot use a fresh batch timestamp');
assert.equal(confirmation({...card,psa10ObservedAt:null},at(0),{meta,sourceRun}),null);
const receipt={version:1,observedAt:'2026-10-14T03:00:00Z',payloadHash:'verified-payload',cards:{fixture:[identity(card),200]}};
assert(confirmation(card,'2026-10-14',{receipt,meta,sourceRun}), 'actual unchanged price response on a new day is an observation');
assert.equal(confirmation({...card,snkPsa10Price:201},'2026-10-14',{receipt}),null);
assert.equal(confirmation({...card,identityKey:'mirror'},'2026-10-14',{receipt}),null);
assert.equal(confirmation(card,'2026-10-15',{receipt}),null,'saved receipt cannot become a future observation');
for (const bad of [{...card,language:'en'},{...card,identityReviewRequired:true},{...card,snkPsa10Price:Infinity}]) assert.equal(confirmation(bad,at(0),{meta,sourceRun}),null);
const history={cards:{fixture:Array.from({length:400},(_,i)=>row(i))},dates:[]};
appendCurrent(history,[card],at(0),{meta,sourceRun});
assert.equal(HISTORY_DAYS,365);assert.equal(history.cards.fixture.length,365);
const before=JSON.stringify(history.cards.fixture.at(-1));
appendCurrent(history,[{...card,snkPsa10Price:999}],at(0),{meta,sourceRun:{...sourceRun,status:'failed'}});
assert.equal(JSON.stringify(history.cards.fixture.at(-1)),before,'failed fetch cannot replace the saved good same-day observation');
appendCurrent(history,[card],at(0),{meta,sourceRun});assert.equal(history.cards.fixture.length,365);
appendCurrent(history,[card],'2026-10-14',{meta,sourceRun:{...sourceRun,status:'failed'}});
assert.equal(history.cards.fixture.at(-1)[0],at(0),'failed acquisition on a later day cannot create a new historical point');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const fixture=fs.mkdtempSync(path.join(os.tmpdir(),'psa-observation-window-'));
try {
  for (const dir of ['data','work']) fs.mkdirSync(path.join(fixture,dir));
  fs.writeFileSync(path.join(fixture,'data/pokemon-cards.json'),JSON.stringify([card]));
  fs.writeFileSync(path.join(fixture,'data/pokemon-cards-meta.json'),JSON.stringify({updatedAt:at(0)}));
  fs.writeFileSync(path.join(fixture,'work/market_stability_history.json'),JSON.stringify({dates:[at(0)],cards:{fixture:[row(0)]}}));
  build(fixture,new Date('2026-10-16T03:00:00Z'));
  const summary=JSON.parse(fs.readFileSync(path.join(fixture,'data/psa10-period-summary.json')));
  assert.equal(summary.asOf,'2026-10-16','failed source date cannot freeze the observation clock');
  assert.equal(summary.cards.fixture[11],3,'latest observation becomes stale, not today');
  assert.equal(summary.cards.fixture[10],1);
} finally {
  assert.equal(path.dirname(fixture),path.resolve(os.tmpdir()));
  assert(path.basename(fixture).startsWith('psa-observation-window-'));
  fs.rmSync(fixture,{recursive:true,force:true});
}
console.log('200 calendar-day boundary, one/day, median, null/stale/failed identity evidence, legacy compatibility and 365-day retention PASS');
