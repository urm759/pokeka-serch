assert.equal(select([fixture],queue,{cards:{}},Date.now(),10,{fixture:{recovery:true}}).length,1,'stale purchase evidence can enter exact-URL discovery even with an old saved price');
assert.equal(select([fixture],queue,{cards:{fixture:{held:true}}},Date.now(),10,{fixture:{recovery:true}}).length,0,'recovery never overrides a manual identity hold');
