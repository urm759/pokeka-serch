const assert=require('node:assert/strict');
const {mergeProfileTargets}=require('./reconcile_saved_source_merge');
const {mergeFixedFreshness}=require('./reconcile_saved_source_merge');
const a={at:'2026-10-23T22:00:00Z',profiles:[{id:'A',urlHash:'same',urlsMatched:['old'],seenQualified:['older']}],pendingDepartures:[{profile:'A',id:'new'},{profile:'A',id:'unresolved'}]};
const b={at:'2026-10-24T02:00:00Z',profiles:[{id:'A',urlHash:'same',urlsMatched:['new'],seenQualified:['new']}],pendingDepartures:[{profile:'A',id:'old',reason:'expired'}],readyRoutes:{shop:['latest']}};
const x=mergeProfileTargets({},a,b);
assert.equal(x.profiles.length,1);assert.deepEqual(x.profiles[0].urlsMatched,['new']);
assert.deepEqual(new Set(x.profiles[0].seenQualified),new Set(['older','old','new']));
assert.deepEqual(x.readyRoutes,b.readyRoutes);assert(!x.pendingDepartures.some(r=>r.id==='new'));
assert(x.pendingDepartures.some(r=>r.id==='unresolved'));
assert.equal(x.pendingDepartures.find(r=>r.id==='old').reason,'expired');
assert.equal(mergeProfileTargets({},b,a).at,b.at);
assert.throws(()=>mergeProfileTargets({},a,{...b,profiles:[b.profiles[0],b.profiles[0]]}));
assert(!mergeProfileTargets({},a,{...b,profiles:[{...b.profiles[0],urlHash:'changed'}]}).profiles[0].seenQualified.includes('old'));
const snapshot=(at,confirmed)=>({cohort:['card'],observations:[{at}],lastConfirmedRows:[{id:'card',lastConfirmedAt:confirmed}],intervalMinima:[]});
const early=snapshot('2026-10-23T22:00:00Z','2026-10-23T20:00:00Z');
const late=snapshot('2026-10-24T02:00:00Z','2026-10-24T01:50:00Z');
const fresh=mergeFixedFreshness({}, {sources:{shop:early}}, {sources:{shop:late}}).sources.shop;
assert.equal(fresh.observations.length,2);assert.deepEqual(fresh.lastConfirmedRows,late.lastConfirmedRows);
assert.equal(require('./proactive_refresh').intervalMinimum(fresh.lastConfirmedRows,fresh.cohort,Date.parse('2026-10-24T02:00:00Z'),Date.parse('2026-10-24T02:40:00Z')).fresh,1);
assert.throws(()=>mergeFixedFreshness({}, {sources:{shop:early}}, {sources:{shop:{...late,cohort:['different']}}}));
console.log('PASS profile snapshots stay unique, latest IDs/settings retained, seen-history union, resolved departures excluded');
