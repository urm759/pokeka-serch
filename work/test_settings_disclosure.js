const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { correction } = require('../settings-disclosure');
assert.equal(correction(600, 600, 300, 9000), 300);
assert.equal(correction(600, 800, 300, 9000), 500);
assert.equal(correction(600, 400, 300, 9000), 100);
assert.equal(correction(600, 200, 300, 9000), 0);
assert.equal(correction(600, 900, 300, 500), 500);
assert.equal(correction(NaN, 900, 300, 500), null);
const root = path.join(__dirname, '..');
const js = fs.readFileSync(path.join(root, 'settings-disclosure.js'), 'utf8');
assert(js.includes("details.closest('.search-settings')"));
assert(js.includes("pending !== current"));
assert(js.includes("'wheel', cancel") && js.includes("'touchmove', cancel"));
assert(!/appendChild|prepend|\.open\s*=|fetch\(/.test(js));
const css = fs.readFileSync(path.join(root, 'styles.css'), 'utf8');
assert(css.includes('.advanced-filters[open]>summary::after'));
assert(!/\.advanced-filters\[open\][^{]*\{[^}]*order\s*:/.test(css));
assert(fs.readFileSync(path.join(root, 'index.html'), 'utf8').includes('settings-disclosure.js'));
console.log('Settings disclosure: anchor correction, boundaries, no reorder/no calculation PASS');
